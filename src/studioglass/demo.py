"""Neutral interactive gallery: python -m studioglass."""
import argparse
import sys
from pathlib import Path
from . import ThemeController, GlassSurface, GlassPanel, GlassButton, GlassSegmentedControl, GlassComboBox, AppearancePopup
from .qt import QtCore as C, QtGui as G, QtWidgets as W, BINDING


def create_demo(mode="light", motion=True):
    window = GlassSurface()
    window.setWindowTitle(f"Studio Glass Qt — {BINDING}")
    window.resize(980,680)
    window.setMinimumSize(700,520)
    theme = ThemeController(window,mode=mode,motion=motion)
    root = W.QVBoxLayout(window)
    root.setContentsMargins(32,24,32,24)
    root.setSpacing(22)
    toolbar = W.QHBoxLayout()
    brand = W.QLabel("STUDIO GLASS")
    font = brand.font()
    font.setBold(True)
    font.setPointSize(12)
    brand.setFont(font)
    toolbar.addWidget(brand)
    toolbar.addStretch()
    nav = GlassSegmentedControl()
    nav.setAccessibleName("Gallery pages")
    for title in ("Overview", "Controls", "Integration"):
        nav.addTab(title)
    theme_button = GlassButton("Dark mode")
    theme_button.setMinimumWidth(132)
    theme_button.setAccessibleName("Toggle light and dark theme")
    theme_button.clicked.connect(lambda: theme.configure(mode="dark" if theme.effective_mode=="light" else "light"))
    theme.changed.connect(lambda: theme_button.setText("Dark mode" if theme.effective_mode=="light" else "Light mode"))
    toolbar.addWidget(theme_button)
    appearance_button = GlassButton("Appearance")
    popup = AppearancePopup(theme)
    appearance_button.clicked.connect(lambda: popup.open_near(appearance_button))
    toolbar.addWidget(appearance_button)
    root.addLayout(toolbar)
    root.addWidget(nav,0,C.Qt.AlignmentFlag.AlignHCenter)
    stack = W.QStackedWidget()
    root.addWidget(stack,1)
    nav.currentChanged.connect(stack.setCurrentIndex)

    overview = W.QWidget()
    content = W.QVBoxLayout(overview)
    content.setContentsMargins(0,0,0,0)
    title = W.QLabel("A lighter layer for your desktop.")
    font = title.font()
    font.setPointSize(25)
    font.setBold(True)
    title.setFont(font)
    title.setWordWrap(True)
    content.addWidget(title)
    description = W.QLabel("Original Qt painting · Native interaction · One small package")
    content.addWidget(description)
    content.addSpacing(8)
    panel = GlassPanel()
    panel_layout = W.QVBoxLayout(panel)
    panel_layout.setContentsMargins(28,26,28,26)
    panel_layout.setSpacing(16)
    panel_layout.addWidget(W.QLabel("YOUR NEXT PROJECT"))
    info = W.QLabel("Use the glass where you navigate and act.\nKeep documents, images and working content clear.")
    info.setWordWrap(True)
    panel_layout.addWidget(info)
    combo = GlassComboBox()
    combo.setAccessibleName("Sample workspace")
    combo.addItem("Design workspace", "design")
    combo.addItem("Research workspace", "research")
    combo.addItem("中文项目 · Unicode support", "unicode")
    panel_layout.addWidget(combo)
    row = W.QHBoxLayout()
    action = GlassButton("Try an action",variant="primary")
    status = W.QLabel("Ready")
    clicks = [0]
    def clicked():
        clicks[0] += 1
        status.setText(f"Action received immediately · {clicks[0]}")
    action.clicked.connect(clicked)
    row.addWidget(action)
    row.addWidget(status,1)
    panel_layout.addLayout(row)
    content.addWidget(panel)
    content.addStretch()
    stack.addWidget(overview)

    controls = W.QWidget()
    form = W.QFormLayout(controls)
    form.setContentsMargins(0,0,0,0)
    form.setVerticalSpacing(22)
    for variant in ("glass","primary","secondary"):
        button = GlassButton(variant.title()+" button",variant=variant)
        button.setIcon(window.style().standardIcon(W.QStyle.StandardPixmap.SP_DialogApplyButton))
        form.addRow(variant.title(),button)
    toggle = GlassButton("Native checkable button",variant="secondary")
    toggle.setCheckable(True)
    form.addRow("Toggle",toggle)
    disabled = GlassButton("Disabled")
    disabled.setEnabled(False)
    form.addRow("Disabled",disabled)
    entry = W.QLineEdit()
    entry.setPlaceholderText("A normal Qt input keeps its normal behavior")
    form.addRow("Plain Qt",entry)
    stack.addWidget(controls)

    integration = W.QWidget()
    column = W.QVBoxLayout(integration)
    column.setContentsMargins(0,0,0,0)
    explanation = W.QLabel("Start with one control.\n\nAttach ThemeController to any QWidget or QMainWindow.\nReplace a QPushButton, QTabBar or QComboBox.\nConnect the standard Qt signals to your existing code.\n\nNo engine, configuration file, global stylesheet or desktop capture is required.")
    explanation.setWordWrap(True)
    column.addWidget(explanation)
    column.addStretch()
    stack.addWidget(integration)
    footer = W.QLabel("60% glass by default · Keyboard friendly · Motion can be disabled in Appearance")
    footer.setWordWrap(True)
    root.addWidget(footer)
    theme.configure(mode=mode)
    return window,theme


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--theme",choices=("light","dark","system"),default="light")
    parser.add_argument("--no-motion",action="store_true")
    parser.add_argument("--snapshot",type=Path,help="Save an offscreen-renderable widget image, then exit")
    args = parser.parse_args()
    app = W.QApplication.instance() or W.QApplication(sys.argv[:1])
    window,theme = create_demo(args.theme,not args.no_motion)
    window.show()
    if args.snapshot:
        def save():
            args.snapshot.parent.mkdir(parents=True,exist_ok=True)
            if not window.grab().save(str(args.snapshot)):
                print("Could not save snapshot",file=sys.stderr)
                app.exit(1)
            else:
                app.quit()
        C.QTimer.singleShot(150,save)
    return app.exec()
